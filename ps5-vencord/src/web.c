/* Se ejecuta antes que Discord y que Vencord:
 *  - hace que el navegador de la PS5 parezca Chrome (Discord bloquea
 *    navegadores que no reconoce),
 *  - implementa GM_xmlhttpRequest / unsafeWindow, que el userscript de
 *    Vencord espera de Tampermonkey, usando el puente /__vc/fetch. */
const char VC_PRELUDE_JS[] =
  "(function(){\n"
  "  'use strict';\n"
  "  var UA = '" VC_SPOOF_UA "';\n"
  "  function def(o, k, v){ try { Object.defineProperty(o, k, {get: function(){ return v; }, configurable: true}); } catch(e){} }\n"
  "  def(Navigator.prototype, 'userAgent', UA);\n"
  "  def(Navigator.prototype, 'appVersion', UA.slice(8));\n"
  "  def(Navigator.prototype, 'vendor', 'Google Inc.');\n"
  "  def(Navigator.prototype, 'platform', 'Win32');\n"
  "  window.unsafeWindow = window;\n"
  "  window.GM_xmlhttpRequest = function(d){\n"
  "    var ctl = typeof AbortController === 'function' ? new AbortController() : null;\n"
  "    var opts = { method: d.method || 'GET', headers: Object.assign({}, d.headers || {}, {'X-Vc-Fetch': '1'}),\n"
  "                 credentials: 'omit', signal: ctl ? ctl.signal : undefined };\n"
  "    if (d.data != null && opts.method !== 'GET' && opts.method !== 'HEAD') opts.body = d.data;\n"
  "    var timer = d.timeout ? setTimeout(function(){ if (ctl) ctl.abort(); d.ontimeout && d.ontimeout(); }, d.timeout) : 0;\n"
  "    fetch('/__vc/fetch?url=' + encodeURIComponent(d.url), opts).then(function(r){\n"
  "      return r.blob().then(function(b){\n"
  "        var hs = ''; r.headers.forEach(function(v, k){ hs += k + ': ' + v + '\\r\\n'; });\n"
  "        var base = { status: r.status, statusText: r.statusText, responseHeaders: hs, finalUrl: d.url, readyState: 4 };\n"
  "        if (d.responseType === 'blob') { base.response = b; return base; }\n"
  "        if (d.responseType === 'arraybuffer') return b.arrayBuffer().then(function(ab){ base.response = ab; return base; });\n"
  "        return b.text().then(function(t){\n"
  "          base.responseText = t; base.response = t;\n"
  "          if (d.responseType === 'json') { try { base.response = JSON.parse(t); } catch(e) { base.response = null; } }\n"
  "          return base;\n"
  "        });\n"
  "      });\n"
  "    }).then(function(res){ clearTimeout(timer); d.onload && d.onload(res); d.onloadend && d.onloadend(res); },\n"
  "            function(err){ clearTimeout(timer); if (err && err.name === 'AbortError') { d.onabort && d.onabort(); } else { d.onerror && d.onerror(err); } });\n"
  "    return { abort: function(){ if (ctl) ctl.abort(); } };\n"
  "  };\n"
  "  window.GM_info = { script: { name: 'Vencord', version: 'ps5' }, scriptHandler: 'Vencord PS5' };\n"
  "})();\n";


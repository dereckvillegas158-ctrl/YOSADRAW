import type { ColorProfile } from './types';

/**
 * Perfiles ICC v2.4 generados a partir de su definición colorimétrica
 * (primarios, blanco D65 y curva de transferencia sRGB), con los colorantes
 * adaptados a D50 por Bradford como exige el estándar.
 */
type M3 = [number, number, number, number, number, number, number, number, number];
type V3 = [number, number, number];

export const mul = (a: M3, b: M3): M3 => [
  a[0] * b[0] + a[1] * b[3] + a[2] * b[6], a[0] * b[1] + a[1] * b[4] + a[2] * b[7], a[0] * b[2] + a[1] * b[5] + a[2] * b[8],
  a[3] * b[0] + a[4] * b[3] + a[5] * b[6], a[3] * b[1] + a[4] * b[4] + a[5] * b[7], a[3] * b[2] + a[4] * b[5] + a[5] * b[8],
  a[6] * b[0] + a[7] * b[3] + a[8] * b[6], a[6] * b[1] + a[7] * b[4] + a[8] * b[7], a[6] * b[2] + a[7] * b[5] + a[8] * b[8],
];
export const apply = (m: M3, v: V3): V3 => [m[0] * v[0] + m[1] * v[1] + m[2] * v[2], m[3] * v[0] + m[4] * v[1] + m[5] * v[2], m[6] * v[0] + m[7] * v[1] + m[8] * v[2]];
export function inv(m: M3): M3 {
  const [a, b, c, d, e, f, g, h, i] = m;
  const A = e * i - f * h, B = -(d * i - f * g), C = d * h - e * g;
  const det = a * A + b * B + c * C;
  return [A / det, -(b * i - c * h) / det, (b * f - c * e) / det, B / det, (a * i - c * g) / det, -(a * f - c * d) / det, C / det, -(a * h - b * g) / det, (a * e - b * d) / det];
}
const xyz = (x: number, y: number): V3 => [x / y, 1, (1 - x - y) / y];

export interface Primaries { r: [number, number]; g: [number, number]; b: [number, number]; white: [number, number] }
export const SRGB: Primaries = { r: [0.64, 0.33], g: [0.3, 0.6], b: [0.15, 0.06], white: [0.3127, 0.329] };
export const DISPLAY_P3: Primaries = { r: [0.68, 0.32], g: [0.265, 0.69], b: [0.15, 0.06], white: [0.3127, 0.329] };
export const D50: V3 = [0.9642, 1, 0.8249];

/** Matriz RGB lineal → XYZ (con el blanco propio del espacio). */
export function rgbToXyz(p: Primaries): M3 {
  const R = xyz(...p.r), G = xyz(...p.g), B = xyz(...p.b), W = xyz(...p.white);
  const P: M3 = [R[0], G[0], B[0], R[1], G[1], B[1], R[2], G[2], B[2]];
  const S = apply(inv(P), W);
  return [P[0] * S[0], P[1] * S[1], P[2] * S[2], P[3] * S[0], P[4] * S[1], P[5] * S[2], P[6] * S[0], P[7] * S[1], P[8] * S[2]];
}

const BRADFORD: M3 = [0.8951, 0.2664, -0.1614, -0.7502, 1.7135, 0.0367, 0.0389, -0.0685, 1.0296];
export function bradford(src: V3, dst: V3): M3 {
  const s = apply(BRADFORD, src), d = apply(BRADFORD, dst);
  return mul(inv(BRADFORD), mul([d[0] / s[0], 0, 0, 0, d[1] / s[1], 0, 0, 0, d[2] / s[2]], BRADFORD));
}

/** Colorantes (columnas) adaptados a D50 para las etiquetas rXYZ/gXYZ/bXYZ. */
export function d50Colorants(p: Primaries): M3 { return mul(bradford(xyz(...p.white), D50), rgbToXyz(p)); }

/** Curva de transferencia sRGB (también la usa Display P3): valor → luz lineal. */
export const srgbDecode = (v: number) => (v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
export const srgbEncode = (l: number) => (l <= 0.0031308 ? l * 12.92 : 1.055 * Math.pow(l, 1 / 2.4) - 0.055);

/* ---------- Escritura binaria del perfil ---------- */

class W {
  buf: number[] = [];
  u8(v: number) { this.buf.push(v & 255); }
  u16(v: number) { this.u8(v >> 8); this.u8(v); }
  u32(v: number) { this.u16((v >>> 16) & 0xffff); this.u16(v & 0xffff); }
  s15(v: number) { this.u32(Math.round(v * 65536) | 0); }
  sig(s: string) { for (let i = 0; i < 4; i++) this.u8(s.charCodeAt(i)); }
  pad4() { while (this.buf.length % 4) this.u8(0); }
}

function tagXYZ(v: V3) { const w = new W(); w.sig('XYZ '); w.u32(0); v.forEach(x => w.s15(x)); return w.buf; }
function tagCurve() {
  const w = new W(); w.sig('curv'); w.u32(0);
  const n = 1024;
  w.u32(n);
  for (let i = 0; i < n; i++) w.u16(Math.round(srgbDecode(i / (n - 1)) * 65535));
  return w.buf;
}
function tagText(s: string) { const w = new W(); w.sig('text'); w.u32(0); for (const c of s) w.u8(c.charCodeAt(0)); w.u8(0); return w.buf; }
function tagDesc(s: string) {
  const w = new W(); w.sig('desc'); w.u32(0);
  w.u32(s.length + 1); for (const c of s) w.u8(c.charCodeAt(0)); w.u8(0);
  w.u32(0); w.u32(0); // Unicode: idioma y longitud
  w.u16(0); w.u8(0); for (let i = 0; i < 67; i++) w.u8(0); // ScriptCode
  return w.buf;
}

export const PROFILE_NAMES: Record<ColorProfile, string> = { srgb: 'sRGB IEC61966-2.1', p3: 'Display P3', gray: 'Gray Gamma sRGB' };

/** Perfil ICC binario para el espacio de color indicado. */
export function makeIccProfile(kind: ColorProfile, date = new Date(Date.UTC(2026, 0, 1))): Uint8Array {
  const tags: [string, number[]][] = [['desc', tagDesc(PROFILE_NAMES[kind])], ['cprt', tagText('No copyright, use freely. Generated by YOSADRAW.')], ['wtpt', tagXYZ(D50)]];
  if (kind === 'gray') tags.push(['kTRC', tagCurve()]);
  else {
    const c = d50Colorants(kind === 'p3' ? DISPLAY_P3 : SRGB);
    tags.push(['rXYZ', tagXYZ([c[0], c[3], c[6]])], ['gXYZ', tagXYZ([c[1], c[4], c[7]])], ['bXYZ', tagXYZ([c[2], c[5], c[8]])]);
    const curve = tagCurve();
    tags.push(['rTRC', curve], ['gTRC', curve], ['bTRC', curve]);
  }
  // Datos de etiquetas (las curvas idénticas se comparten).
  const data = new W();
  const table: [string, number, number][] = [];
  const shared = new Map<number[], number>();
  const base = 128 + 4 + tags.length * 12;
  for (const [sig, bytes] of tags) {
    let off = shared.get(bytes);
    if (off === undefined) { data.pad4(); off = base + data.buf.length; data.buf.push(...bytes); shared.set(bytes, off); }
    table.push([sig, off, bytes.length]);
  }
  data.pad4();
  const size = base + data.buf.length;
  const h = new W();
  h.u32(size); h.u32(0); h.u32(0x02400000); h.sig('mntr'); h.sig(kind === 'gray' ? 'GRAY' : 'RGB '); h.sig('XYZ ');
  h.u16(date.getUTCFullYear()); h.u16(date.getUTCMonth() + 1); h.u16(date.getUTCDate()); h.u16(0); h.u16(0); h.u16(0);
  h.sig('acsp'); h.u32(0); h.u32(0); h.u32(0); h.u32(0); h.u32(0); h.u32(0); // plataforma, flags, fabricante, modelo, atributos (8 bytes)
  h.u32(0); // intención perceptual
  D50.forEach(x => h.s15(x));
  h.u32(0); // creador
  for (let i = 0; i < 16 + 28; i++) h.u8(0); // ID de perfil + reservado
  h.u32(tags.length);
  for (const [sig, off, len] of table) { h.sig(sig); h.u32(off); h.u32(len); }
  return new Uint8Array([...h.buf, ...data.buf]);
}
